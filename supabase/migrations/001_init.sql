-- 1. Habilitar extensão para exclusão com btree_gist (necessária para daterange e UUID)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 2. Tabela: profiles
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  telefone TEXT,
  tipo TEXT NOT NULL CHECK (tipo IN ('locatario', 'anunciante')),
  nome_loja TEXT,
  cidade TEXT,
  descricao_loja TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- Garantir que tipo de usuário não possa ser alterado posteriormente pelo usuário
CREATE OR REPLACE FUNCTION public.prevent_profile_tipo_change()
RETURNS TRIGGER AS $$
BEGIN
  IF OLD.tipo IS DISTINCT FROM NEW.tipo THEN
    RAISE EXCEPTION 'Não é permitido alterar o tipo de conta após a criação.';
  END IF;
  NEW.updated_at = timezone('utc', now());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trg_prevent_profile_tipo_change ON public.profiles;
CREATE TRIGGER trg_prevent_profile_tipo_change
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.prevent_profile_tipo_change();

-- 3. Tabela: products
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  titulo TEXT NOT NULL,
  categoria TEXT NOT NULL,
  tamanhos TEXT[] NOT NULL DEFAULT '{}',
  preco_diaria NUMERIC(10, 2) NOT NULL CHECK (preco_diaria > 0),
  caucao NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (caucao >= 0),
  descricao TEXT NOT NULL,
  medidas JSONB NOT NULL DEFAULT '{}'::jsonb,
  imagens TEXT[] NOT NULL DEFAULT '{}',
  art_type TEXT,
  art_color TEXT,
  rating NUMERIC(3, 1) DEFAULT 5.0,
  reviews INT DEFAULT 0,
  ativo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(categoria);
CREATE INDEX IF NOT EXISTS idx_products_owner ON public.products(owner_id);
CREATE INDEX IF NOT EXISTS idx_products_ativo ON public.products(ativo);

-- 4. Tabela: reservations
CREATE TABLE IF NOT EXISTS public.reservations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo TEXT NOT NULL UNIQUE,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  renter_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  tamanho TEXT,
  data_inicio DATE NOT NULL,
  data_fim DATE NOT NULL CHECK (data_fim >= data_inicio),
  dias INT NOT NULL CHECK (dias > 0),
  valor_diarias NUMERIC(10, 2) NOT NULL CHECK (valor_diarias >= 0),
  valor_caucao NUMERIC(10, 2) NOT NULL CHECK (valor_caucao >= 0),
  valor_total NUMERIC(10, 2) NOT NULL CHECK (valor_total >= 0),
  status TEXT NOT NULL DEFAULT 'aguardando_pagamento' 
    CHECK (status IN ('aguardando_pagamento', 'paga', 'cancelada', 'expirada')),
  expires_at TIMESTAMPTZ NOT NULL,
  mp_preference_id TEXT,
  mp_payment_id TEXT,
  metodo_pagamento TEXT,
  repasse_status TEXT NOT NULL DEFAULT 'pendente' 
    CHECK (repasse_status IN ('pendente', 'repassado', 'nao_aplicavel')),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),

  -- Constraint de exclusão para evitar overbooking (períodos sobrepostos)
  -- Períodos no Postgres daterange [inicio, fim] são fechados
  CONSTRAINT no_overlapping_reservations EXCLUDE USING gist (
    product_id WITH =,
    daterange(data_inicio, data_fim, '[]') WITH &&
  ) WHERE (status IN ('paga', 'aguardando_pagamento'))
);

CREATE INDEX IF NOT EXISTS idx_reservations_renter ON public.reservations(renter_id);
CREATE INDEX IF NOT EXISTS idx_reservations_product ON public.reservations(product_id);
CREATE INDEX IF NOT EXISTS idx_reservations_status ON public.reservations(status);

-- 5. Função de expiração de reservas vencidas (idempotente)
CREATE OR REPLACE FUNCTION public.expirar_reservas_vencidas()
RETURNS INT AS $$
DECLARE
  afetadas INT;
BEGIN
  UPDATE public.reservations
  SET status = 'expirada',
      updated_at = timezone('utc', now())
  WHERE status = 'aguardando_pagamento'
    AND expires_at < timezone('utc', now());
    
  GET DIAGNOSTICS afetadas = ROW_COUNT;
  RETURN afetadas;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 6. Trigger para auto-criação de perfil a partir do auth.users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  v_nome TEXT;
  v_tipo TEXT;
  v_telefone TEXT;
  v_nome_loja TEXT;
  v_cidade TEXT;
  v_descricao_loja TEXT;
  v_lgpd_at TIMESTAMPTZ;
  v_lgpd_version TEXT;
BEGIN
  v_nome := COALESCE(NEW.raw_user_meta_data->>'nome', split_part(NEW.email, '@', 1));
  v_tipo := COALESCE(NEW.raw_user_meta_data->>'tipo', 'locatario');
  v_telefone := NEW.raw_user_meta_data->>'telefone';
  v_nome_loja := NEW.raw_user_meta_data->>'nome_loja';
  v_cidade := NEW.raw_user_meta_data->>'cidade';
  v_descricao_loja := NEW.raw_user_meta_data->>'descricao_loja';
  v_lgpd_at := NULLIF(NEW.raw_user_meta_data->>'consentimento_lgpd_at', '')::TIMESTAMPTZ;
  v_lgpd_version := NEW.raw_user_meta_data->>'consentimento_lgpd_versao';

  IF v_tipo NOT IN ('locatario', 'anunciante', 'ambos') THEN
    v_tipo := 'locatario';
  END IF;

  INSERT INTO public.profiles (
    id, nome, telefone, tipo, nome_loja, cidade, descricao_loja,
    consentimento_lgpd_at, consentimento_lgpd_versao, created_at, updated_at
  ) VALUES (
    NEW.id, v_nome, v_telefone, v_tipo, v_nome_loja, v_cidade, v_descricao_loja,
    v_lgpd_at, v_lgpd_version,
    timezone('utc', now()), timezone('utc', now())
  )
  ON CONFLICT (id) DO UPDATE SET
    nome = EXCLUDED.nome,
    telefone = COALESCE(EXCLUDED.telefone, public.profiles.telefone),
    nome_loja = COALESCE(EXCLUDED.nome_loja, public.profiles.nome_loja),
    cidade = COALESCE(EXCLUDED.cidade, public.profiles.cidade),
    descricao_loja = COALESCE(EXCLUDED.descricao_loja, public.profiles.descricao_loja),
    consentimento_lgpd_at = COALESCE(EXCLUDED.consentimento_lgpd_at, public.profiles.consentimento_lgpd_at),
    consentimento_lgpd_versao = COALESCE(EXCLUDED.consentimento_lgpd_versao, public.profiles.consentimento_lgpd_versao),
    updated_at = timezone('utc', now());

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();

-- 7. Função RPC pública segura para calendário de disponibilidade
-- Expõe SOMENTE as datas ocupadas e o id do produto (NENHUM dado pessoal de locatário)
CREATE OR REPLACE FUNCTION public.get_datas_ocupadas(p_product_id BIGINT)
RETURNS TABLE (data_inicio DATE, data_fim DATE) AS $$
BEGIN
  -- Executa expiração rápida antes de checar
  PERFORM public.expirar_reservas_vencidas();

  RETURN QUERY
  SELECT r.data_inicio, r.data_fim
  FROM public.reservations r
  WHERE r.product_id = p_product_id
    AND r.status IN ('paga', 'aguardando_pagamento')
    AND r.expires_at > timezone('utc', now())
  ORDER BY r.data_inicio ASC;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;

-- 8. Configuração de Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;

-- ── RLS: profiles ──
-- Qualquer pessoa pode visualizar informações públicas de lojas/anunciantes (nome_loja, cidade, descricao_loja)
CREATE POLICY "Lojas com visualização pública"
  ON public.profiles FOR SELECT
  USING (tipo IN ('anunciante', 'ambos'));

-- Usuário autenticado pode ler seu próprio perfil completo (incluindo email, telefone)
CREATE POLICY "Usuário lê o próprio perfil"
  ON public.profiles FOR SELECT
  TO authenticated
  USING (auth.uid() = id);

-- Usuário autenticado atualiza apenas o próprio perfil (trigger impede mudar tipo)
CREATE POLICY "Usuário atualiza o próprio perfil"
  ON public.profiles FOR UPDATE
  TO authenticated
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

-- ── RLS: products ──
-- Qualquer pessoa (anônima ou autenticada) pode listar peças ativas
CREATE POLICY "Visualização pública de produtos ativos"
  ON public.products FOR SELECT
  USING (ativo = true);

-- Anunciante vê todos os seus produtos (ativos ou inativos)
CREATE POLICY "Anunciante vê todos os seus produtos"
  ON public.products FOR SELECT
  TO authenticated
  USING (auth.uid() = owner_id);

-- Apenas perfil 'anunciante' pode inserir produto para si mesmo
CREATE POLICY "Apenas anunciante insere produto"
  ON public.products FOR INSERT
  TO authenticated
  WITH CHECK (
    auth.uid() = owner_id AND
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid() AND profiles.tipo = 'anunciante'
    )
  );

-- Apenas o dono pode atualizar seu produto
CREATE POLICY "Dono atualiza seu produto"
  ON public.products FOR UPDATE
  TO authenticated
  USING (auth.uid() = owner_id)
  WITH CHECK (auth.uid() = owner_id);

-- Apenas o dono pode excluir seu produto
CREATE POLICY "Dono remove seu produto"
  ON public.products FOR DELETE
  TO authenticated
  USING (auth.uid() = owner_id);

-- ── RLS: reservations ──
-- Locatário lê suas próprias reservas
CREATE POLICY "Locatário lê suas reservas"
  ON public.reservations FOR SELECT
  TO authenticated
  USING (auth.uid() = renter_id);

-- Anunciante lê reservas feitas para seus produtos
CREATE POLICY "Anunciante lê reservas de seus produtos"
  ON public.reservations FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.products
      WHERE products.id = reservations.product_id
        AND products.owner_id = auth.uid()
    )
  );

-- INSERÇÃO / ATUALIZAÇÃO de reservas:
-- NENHUM usuário pelo frontend insere ou atualiza direto a tabela reservations.
-- Toda criação, cálculo e atualização de status é feita exclusivamente
-- pela Edge Function com a Service Role Key (bypassa RLS com segurança absoluta).

-- 9. Storage: Bucket 'produtos'
-- Inserção de registro do bucket caso não exista
INSERT INTO storage.buckets (id, name, public)
VALUES ('produtos', 'produtos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Políticas de Storage
-- Leitura pública de qualquer imagem de produto
CREATE POLICY "Visualização pública de imagens de produtos"
  ON storage.objects FOR SELECT
  USING (bucket_id = 'produtos');

-- Anunciante autenticado só faz upload na pasta do seu próprio user id
CREATE POLICY "Anunciante envia foto para sua pasta"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'produtos' AND
    (storage.foldername(name))[1] = auth.uid()::text AND
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid() AND profiles.tipo = 'anunciante'
    )
  );

-- Anunciante atualiza e remove suas próprias fotos
CREATE POLICY "Anunciante altera foto da sua pasta"
  ON storage.objects FOR UPDATE
  TO authenticated
  USING (
    bucket_id = 'produtos' AND
    (storage.foldername(name))[1] = auth.uid()::text
  );

CREATE POLICY "Anunciante remove foto da sua pasta"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (
    bucket_id = 'produtos' AND
    (storage.foldername(name))[1] = auth.uid()::text
  );
